// `npm run export:contracts` -> contracts/
//   openapi.json                       full HTTP API (generated from the route schemas)
//   schemas/*.schema.json              scene, node types, operations, WebSocket messages
//   types/gallery-api.d.ts             TypeScript types for web clients
// The TypeBox schemas in src/ are the single source of truth; regenerate after changes.
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { compile } from 'json-schema-to-typescript';

// The app is built (not started) only to collect route schemas: no database or storage
// connection is opened, so placeholder settings are enough.
process.env.DATABASE_URL ??= 'postgres://unused@localhost/unused';
process.env.S3_ACCESS_KEY_ID ??= 'unused';
process.env.S3_SECRET_ACCESS_KEY ??= 'unused';
process.env.NODE_ENV = 'test';
process.env.ASSISTANT_PROVIDER = 'disabled';

const { buildApp } = await import('../src/app.js');
const { loadConfig } = await import('../src/config.js');
const { createPool } = await import('../src/db/pool.js');
const { S3Storage } = await import('../src/assets/storage.js');
const { Scene, SceneNode, NODE_SCHEMAS, Environment, ViewerAnchor } = await import('../src/schemas/scene.js');
const { Operation, ActionRequest, WireChange } = await import('../src/schemas/operations.js');
const { ClientMessage, ServerMessage } = await import('../src/realtime/messages.js');
const { Command } = await import('../src/assistant/routes.js');

const out = path.resolve('contracts');
await mkdir(path.join(out, 'schemas'), { recursive: true });
await mkdir(path.join(out, 'types'), { recursive: true });

const config = loadConfig();
config.publicApiUrl = process.env.PUBLIC_API_URL ?? 'https://api.example.com';
const db = createPool(config.databaseUrl, false);
const app = await buildApp({ config, db, storage: new S3Storage(config.s3), assistantProvider: null });
await app.ready();
await writeFile(path.join(out, 'openapi.json'), JSON.stringify(app.swagger(), null, 2));
await app.close();
await db.end();

const schemas: Record<string, unknown> = {
  scene: Scene,
  'scene-node': SceneNode,
  environment: Environment,
  'viewer-anchor': ViewerAnchor,
  operation: Operation,
  'action-request': ActionRequest,
  'wire-change': WireChange,
  'ws-client-message': ClientMessage,
  'ws-server-message': ServerMessage,
  'assistant-command': Command,
  ...Object.fromEntries(Object.entries(NODE_SCHEMAS).map(([t, s]) => [`node-${t}`, s])),
};
for (const [name, s] of Object.entries(schemas))
  await writeFile(
    path.join(out, 'schemas', `${name}.schema.json`),
    JSON.stringify({ $schema: 'http://json-schema.org/draft-07/schema#', $id: `${name}.schema.json`, ...(s as object) }, null, 2),
  );

// TypeScript types (one declaration file, no runtime dependency for clients).
const typeTargets: [string, unknown][] = [
  ['Scene', Scene],
  ['Operation', Operation],
  ['ActionRequest', ActionRequest],
  ['WireChange', WireChange],
  ['WsClientMessage', ClientMessage],
  ['WsServerMessage', ServerMessage],
  ['AssistantCommand', Command],
];
let dts = `// Generated by scripts/export-contracts.ts from the backend TypeBox schemas. Do not edit.\n// Scene conventions: meters, right-handed, +Y up, forward -Z, quaternions [x,y,z,w], colors "#rrggbb".\n\n`;
for (const [name, schema] of typeTargets) {
  const ts = await compile(structuredClone(schema) as any, name, {
    bannerComment: '',
    additionalProperties: false,
    declareExternallyReferenced: true,
    strictIndexSignatures: false,
    format: true,
  });
  dts += `${ts}\n`;
}
// json-schema-to-typescript emits shared sub-types once per root; keep the first declaration.
const seen = new Set<string>();
dts = dts
  .split(/\n(?=export (?:type|interface) )/)
  .filter((block) => {
    const m = /^export (?:type|interface) (\w+)/.exec(block.trimStart());
    if (!m) return true;
    if (seen.has(m[1])) return false;
    seen.add(m[1]);
    return true;
  })
  .join('\n');
await writeFile(path.join(out, 'types', 'gallery-api.d.ts'), dts);

console.log(`contracts written to ${out}: openapi.json, ${Object.keys(schemas).length} JSON Schemas, types/gallery-api.d.ts`);
